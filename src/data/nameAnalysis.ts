const WUXING_MAP: Record<number, string> = {
  1: '木',2: '木', 3: '火',4: '火', 5: '土',6: '土', 7: '金',8: '金', 9: '水',0: '水',
};

function strokesOf(s: string, idx: number): number {
  const ch = s[idx];
  if (ch && CHAR_STROKES[ch]) return CHAR_STROKES[ch];
  if (ch) return Math.max(1, ch.charCodeAt(0) % 20 + 5);
  return 0;
}

function wuxingOf(n: number): string {
  return WUXING_MAP[n % 10] || '土';
}

