export interface AlmanacDay {
  year: number; month: number; day: number;
  weekday: string;          // 星期X
  yearGan: string; yearZhi: string;
  monthGan: string; monthZhi: string;
  dayGan: string; dayZhi: string;
  solarTerm: string;        // 当前节气（近似）
  zodiac: string;
  wuxing: string;
  auspicious: string[];
  inauspicious: string[];
  luckyColors: string[];
  luckyDirection: string;
  fortunes: Array<{ zodiac: string; stars: string; summary: string; detail: string }>;
}

export function getAlmanac(date?: Date): AlmanacDay {
  const d = date || new Date();
  const y = d.getFullYear(), m = d.getMonth() + 1, day = d.getDate();

  const yearPillar = getYearPillar(y, m, day);
  const monthPillar = getMonthPillar(yearPillar.ganIndex, m, day);
  const dayPillar = getDayPillar(y, m, day);

  const dayZhiName = dayPillar.zhi;
  const wx = ZHI_WUXING[dayZhiName] || '土';
  const fortunes = ZODIAC_FORTUNE[dayZhiName] || ZODIAC_FORTUNE['子'];

  return {
    year: y, month: m, day,
    weekday: `星期${'日一二三四五六'[d.getDay()]}`,
    yearGan: yearPillar.gan, yearZhi: yearPillar.zhi,
    monthGan: monthPillar.gan, monthZhi: monthPillar.zhi,
    dayGan: dayPillar.gan, dayZhi: dayZhiName,
    solarTerm: getSolarTermName(m, day),
    zodiac: ZODIAC[yearPillar.zhiIndex],
    wuxing: wx,
    auspicious: DAY_AUSPICIOUS[dayZhiName] || ['祭祀', '出行'],
    inauspicious: DAY_INAUSPICIOUS[dayZhiName] || ['动土', '安葬'],
    luckyColors: WUXING_COLORS[wx] || ['红色'],
    luckyDirection: WUXING_DIRECTIONS[wx] || '东',
    fortunes: ZODIAC.map((z, i) => {
      const f = fortunes[i % fortunes.length];
      return { zodiac: z, stars: f[0], summary: f[1], detail: f[2] };
    }),
  };
}

